"""Aggregate every result table into report/RESULTS.md and copy report figures to report/figures/.

    python collect_results.py
"""
import glob
import os
import shutil

import pandas as pd

OUT = "report/RESULTS.md"
FIG = "report/figures"
os.makedirs(FIG, exist_ok=True)
pd.set_option("display.width", 250)

SECTIONS = [
    ("Task 1 – clean / colour / patch-shuffle", "task1/results/table_interventions.csv", None),
    ("Task 1 – translation (mean over 4 directions)", "task1/results/translation_curve.csv", None),
    ("Task 1 – shape bias (aggregate rows)", "task1/results/shape_bias.csv", lambda d: d[~d.model.str.contains(r"\|")]),
    ("Task 1 – representation stability (cosine)", "task1/results/representation_stability.csv", None),
    ("Task 1 – prediction change vs representation shift", "task1/results/prediction_vs_representation.csv", None),
    ("Task 2 – main comparison", "task2/results/final_main/table_main.csv", None),
    ("Task 2 – per-class Sketch accuracy", "task2/results/final_main/per_class_target_acc.csv", None),
    ("Task 2 – DAN lambda study", "task2/results/final_lambda_study/table_main.csv", None),
    ("Task 2 – unstable / biased variants (evidence)", "task2/results/final_unstable_variants/table_main.csv", None),
    ("Task 3 – main comparison", "task3/results/final_main/table_main.csv", None),
    ("Task 3 – per-class Sketch accuracy", "task3/results/final_main/per_class_sketch_acc.csv", None),
    ("Task 3 – SAM rho study", "task3/results/final_rho_study/table_main.csv", None),
    ("Task 3 – Task 2 vs Task 3 (target access)", "task3/results/final_main/task2_vs_task3.csv", None),
    ("Task 3 – source-side diagnostics (all models)", "task3/results/source_diagnostics/source_table.csv", None),
    ("Task 4 – post-hoc scores on Vanilla", "task4/results/final/table1_vanilla_scores.csv", None),
    ("Task 4 – trained models", "task4/results/final/table2_models.csv", None),
    ("Task 4 – Vanilla+MLS accepted unknowns", "task4/results/final/vanilla_mls_accepted_unknowns.csv", lambda d: d.groupby("group").head(6)),
    ("Task 4 – acceptance by unknown class", "task4/results/final/vanilla_mls_acceptance_by_unknown_class.csv", None),
]
FIGS = ["task1/results/figures/*.png", "task1/results/images/examples/*.png", "task2/results/final_*/*.png",
        "task3/results/final_*/*.png", "task4/results/final/*.png"]

with open(OUT, "w") as f:
    f.write("# Collected results (auto-generated by collect_results.py)\n\n")
    for title, path, fn in SECTIONS:
        f.write(f"## {title}\n`{path}`\n\n")
        if not os.path.exists(path):
            f.write("_missing_\n\n"); continue
        d = pd.read_csv(path)
        if fn is not None:
            d = fn(d)
        f.write(d.round(4).to_markdown(index=False) + "\n\n")
n = 0
for pat in FIGS:
    for p in glob.glob(pat):
        dst = os.path.join(FIG, p.replace("/", "__").replace("results__", ""))
        shutil.copy(p, dst); n += 1
print(f"wrote {OUT}; copied {n} figures to {FIG}/")
